export const COPY_DEFAULTS: Record<string, string> = Object.fromEntries(
  COPY_ENTRIES.map((entry) => [entry.key, entry.text]),
);

export type Copy = (key: string, vars?: Record<string, string | number>) => string;

/** החלפת {שם} בערך, ואיחוד רווחים כפולים שנוצרים כשמשתנה ריק. */
function fill(text: string, vars?: Record<string, string | number>): string {
  if (!vars) return text.replace(/\s+/g, ' ').trim();
  return text
    .replace(/\{(\w+)\}/g, (whole, name) => {
      const value = vars[name];
      return value === undefined || value === null ? '' : String(value);
    })
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * טעינת הנוסחים, פעם אחת לכל שיחה.
 *
 * כישלון בקריאה אינו מפיל את השיחה: הקו ממשיך עם ברירות המחדל. שלוחה
 * שמדברת בנוסח מעט ישן עדיפה על שלוחה שמשמיעה שגיאה.
 */
export async function loadCopy(client: SupabaseClient): Promise<Copy> {
  let edited: Record<string, string> = {};
  try {
    const { data } = await client.from('igud_ivr_copy').select('key, text');
    for (const row of (data || []) as { key: string; text: string }[]) {
      const text = String(row.text || '').trim();
      if (text) edited[row.key] = text;
    }
  } catch {
    edited = {};
  }

  return (key, vars) => fill(edited[key] ?? COPY_DEFAULTS[key] ?? '', vars);
}

/** נוסחים בלי גישה למסד, לשימוש בבנייה ובבדיקות. */
export const copyDefaults: Copy = (key, vars) => fill(COPY_DEFAULTS[key] ?? '', vars);
