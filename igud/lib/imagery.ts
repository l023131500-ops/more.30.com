/**
 * שכבת התמונות של האתר.
 *
 * לכל אזור רחב באתר יש כאן "משבצת": שם אחד שמייצג רקע. המשבצת יכולה
 * להתמלא בצילום, ואם היא ריקה — מוצג במקומה איור מקורי. כך העמוד נראה
 * שלם גם היום, בלי צילום אחד, וברגע שיאושר בנק תמונות אין צורך לגעת
 * בשום עמוד: משנים כאן שורה אחת לכל משבצת וזהו.
 *
 * שני כללים שנשמרים כאן בכוונה:
 *
 * ראשית, אין כאן כתובת שלא נבדקה. כתובת של תמונה שאינה קיימת אינה
 * שגיאה שנראית בבנייה — היא ריבוע ריק אצל המבקר. לכן המפה מתחילה
 * ריקה, ותתמלא רק בכתובות שנפתחו ונראו.
 *
 * שנית, כל צילום נושא את הייחוס שלו. בנקי תמונות חופשיים אינם דורשים
 * ייחוס בחוק, אבל אתר של איגוד ארצי שמפרסם צילום של בית מדרש צריך
 * לדעת מאיפה הוא הגיע.
 */

export type SceneKey = 'hero' | 'cta' | 'join' | 'centers' | 'rabbis' | 'search';

export interface Photo {
  /** כתובת מלאה. המארח חייב להופיע ב-remotePatterns שב-next.config */
  src: string;
  /** תיאור לקורא מסך. רקע עיטורי בלבד — השאר ריק */
  alt: string;
  /** צלם ובנק התמונות, לתיעוד */
  credit?: string;
  /** מוקד החיתוך, כשהנושא אינו במרכז. למשל '50% 30%' */
  focus?: string;
}

/**
 * המשבצות המלאות. ריק פירושו: הצג את האיור.
 *
 * דוגמה למילוי, כשתאושר גישה:
 *   hero: {
 *     src: 'https://images.unsplash.com/photo-XXXX?auto=format&fit=crop&w=2000&q=75',
 *     alt: '',
 *     credit: 'Unsplash / שם הצלם',
 *     focus: '50% 40%',
 *   },
 */
export const PHOTOS: Partial<Record<SceneKey, Photo>> = {};

export function photoOf(name: SceneKey): Photo | null {
  return PHOTOS[name] ?? null;
}
