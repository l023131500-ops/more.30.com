-- שכבת סיווג: מועד > פרשה > נושא
with base as (
  select seq, subfolder, source, duration_seconds d, topic, coalesce(parsha_or_date,'') pod,
         coalesce(edited_transcript, raw_transcript,'') t
  from recordings
  where deleted_at is null and duration_seconds >= 30
),
hay as (
  select *,
    coalesce(topic,'') || ' ~ ' || pod || ' ~ ' || left(t, 700) as h,
    (left(t,200) ~ 'שבוע טוב') as weekly
  from base
),
moed as (
  select *, case
    when h ~ 'ראש השנה|ימים נוראים|יום הדין' then 'ראש השנה'
    when h ~ 'יום כיפור|יום הכיפורים|כיפור' then 'יום כיפור'
    when h ~ 'סוכות|הושענא רבה|שמחת תורה|שמיני עצרת|ארבעת המינים|סוכה' then 'סוכות ושמחת תורה'
    when h ~ 'חנוכה|נר שמיני|נרות חנוכה' then 'חנוכה'
    when h ~ 'ט"ו בשבט|ט״ו בשבט|טו בשבט|ראש השנה לאילנות' then 'ט״ו בשבט'
    when h ~ 'פורים|מגילה|משלוח מנות|מרדכי ואסתר|תענית אסתר|שושן פורים' then 'פורים'
    when h ~ 'פסח|ליל הסדר|חמץ|מצה|יציאת מצרים|הגדה|שביעי של פסח' then 'פסח'
    when h ~ 'ספירת העומר|ל"ג בעומר|ל״ג בעומר|לג בעומר|רשב"י|רשב״י' then 'ספירת העומר ול״ג בעומר'
    when h ~ 'שבועות|מתן תורה|קבלת התורה|חג הביכורים' then 'שבועות'
    when h ~ 'בין המצרים|תשעה באב|ט. באב|ט״ב|שלושת השבועות|חורבן|צום גדליה|י"ז בתמוז|יז בתמוז|עשרה בטבת' then 'בין המצרים וצומות'
    when h ~ 'אלול|סליחות|חודש הרחמים' then 'אלול וסליחות'
    when h ~ 'ראש חודש|שובבים' then 'ראש חודש'
    else null end as moed
  from hay
),
prsh as (
  select *, case when moed is not null then null else
    (regexp_match(h, '(בראשית|נח|לך לך|וירא|חיי שרה|תולדות|ויצא|וישלח|וישב|מקץ|ויגש|ויחי|שמות|וארא|בא|בשלח|יתרו|משפטים|תרומה|תצוה|תצווה|כי תשא|ויקהל|פקודי|ויקרא|צו|שמיני|תזריע|מצורע|אחרי מות|קדושים|אמור|בהר|בחוקותי|בחוקתי|במדבר|נשא|בהעלותך|שלח|קרח|חוקת|בלק|פינחס|פנחס|מטות|מסעי|דברים|ואתחנן|עקב|ראה|שופטים|כי תצא|כי תבוא|נצבים|ניצבים|וילך|האזינו|וזאת הברכה)', 'g'))[1]
  end as parsha_raw,
  (h ~ 'פרשת|פרשה|בפרשה|ערב שבת קודש') as parsha_ctx
  from moed
)
select * from prsh;
