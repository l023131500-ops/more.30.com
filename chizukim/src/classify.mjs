const NOTICE_RE = /הודעה טכנית|הודעות טכניות|עדכון מספר|הוראות שימוש|הנחיות שימוש|הנחיות ניווט|הפעלת מערכת|שינויים בקו|בעניין שליחת|ניסיון$|^ניסיון/;

/** מסיר את כותרת ה"נושא/תאריך" שנוספה אוטומטית לתמלולים גולמיים */
function stripHeader(t) {
  return (t || '').replace(/^נושא:[^\n]*\n(תאריך:[^\n]*\n)?/, '');
}

/**
 * מסווג רשומה אחת.
 * @returns {{skip?:string, weekly:boolean, cat:number, catName:string, sub:string|null, parsha:string|null}}
 */
export function classify(row) {
  const topic = row.topic || '';
  const pod = row.parsha_or_date || '';
  const body = stripHeader(row.edited_transcript || row.raw_transcript || '');
  // חלון הזיהוי: כותרת + שדה הפרשה/תאריך + פתיחת התמלול, שבה נאמר המועד
  const win = `${topic} ~ ${pod} ~ ${body.slice(0, 300)}`;

  // ההקלטה השבועית נפתחת ב"שבוע טוב"
  const weekly = /שבוע טוב/.test(body.slice(0, 200));

  if (NOTICE_RE.test(topic)) return { skip: 'הודעה טכנית', weekly };
  if (!topic.trim()) return { skip: 'אין כותרת', weekly };

  for (const m of MOADIM) {
    if (m.re.test(win)) return { weekly, cat: 2, catName: 'מועדים וזמנים', sub: m.name, parsha: null };
  }

  const pm = win.match(PARSHA_RE);
  if (pm) {
    const parsha = PARSHA_CANON[pm[1]] || pm[1];
    const chumash = CHUMASHIM.find((c) => c.parshiot.includes(parsha));
    return { weekly, cat: 1, catName: 'פרשות השבוע', sub: chumash ? chumash.name : 'בראשית', parsha };
  }

  for (const t of TOPICS) {
    if (t.re.test(topic)) return { weekly, cat: t.key, catName: t.name, sub: null, parsha: null };
  }
  // בלתי אפשרי — הקטגוריה האחרונה תופסת הכול
  return { weekly, cat: 9, catName: 'משלים, סיפורי צדיקים ועבודת האדם', sub: null, parsha: null };
}
